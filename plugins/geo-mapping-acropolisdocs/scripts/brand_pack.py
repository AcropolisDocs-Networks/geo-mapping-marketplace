def starter() -> dict:
    """data/brand-starter.yaml: the neutral grounds, the placeholder mark and the template's example values (colours are data, not code)."""
    import yaml
    return yaml.safe_load((HERE.parent / "data" / "brand-starter.yaml").read_text(encoding="utf-8"))


def slugify(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", name.strip().lower()).strip("-")
    if s and not s[0].isalpha():
        s = "b-" + s
    return s[:40].rstrip("-")


def _hex(value: str) -> str:
    v = str(value).strip()
    if not re.fullmatch(r"#?[0-9A-Fa-f]{6}", v):
        raise PackError(f"'{value}' is not a colour written as #RRGGBB")
    return cl.norm_hex(v if v.startswith("#") else "#" + v)


def _accents(given: list[str], ground: str, dark: bool) -> list[str]:
    """Five accents for one mode from one to five given colours: each moved until it reads on the mode's ground (3:1, a map mark), the
    missing ones turned from the first by hue (+150, -60 degrees) and by depth, so a one-colour brand still has a full set."""
    out = []
    for c in given[:5]:
        out.append(cl.ensure_contrast(c, ground, 3.0)[0])
    h, l, s = cl.hls(out[0])
    s2 = max(0.35, min(s, 0.75))
    turns = [(h + 150, 0.62 if dark else 0.36, s2), (h - 60, 0.66 if dark else 0.38, s2 * 0.8),
             (h, 0.80 if dark else 0.20, s2 * 0.6), (h + 150, 0.45 if dark else 0.18, s2 * 0.5)]
    for hh, ll, ss in turns[len(out) - 1:]:
        if len(out) >= 5:
            break
        out.append(cl.ensure_contrast(cl.from_hls(hh, ll, ss), ground, 3.0)[0])
    return out[:5]


def _ramp(accent: str, dark: bool) -> list[str]:
    """Seven steps of the accent's own hue: light to deep in print, pale to mid on a dark ground."""
    h, _, s = cl.hls(accent)
    s = max(0.30, min(s, 0.85))
    lights = (0.82, 0.74, 0.66, 0.58, 0.50, 0.42, 0.34) if dark else (0.68, 0.58, 0.48, 0.40, 0.32, 0.25, 0.18)
    return [cl.from_hls(h, x, s) for x in lights]


def placeholder_logo(accent: str, light_ground: bool) -> str:
    """A plain geometric mark for a brand added without a logo, so its maps build: a rounded square in the accent with an open ring.
    No letters (a mark never depends on a font). Replace it by running `set_brand.py new` again with --logo FILE.svg --replace."""
    st = starter()
    inner = st["placeholder_inner"]["on_dark_mark" if cl.luminance(accent) < 0.5 else "on_light_mark"]
    return st["placeholder_logo"].format(accent=accent, inner=inner)


def make_brand(name: str, accents: list[str], *, slug: str | None = None, owner: str | None = None, homepage: str | None = None,
               logo_light: str | None = None, logo_dark: str | None = None, trademark_line: str | None = None, tagline: str | None = None) -> dict:
    """A complete brand (schemas/brand.schema.json) from a name, one to five colours and a logo. The neutrals (page, text, rules) are the
    plugin's own quiet greys; the colours become the accents of both the light and the dark theme, each moved only as far as contrast needs."""
    name = (name or "").strip()
    if not name:
        raise PackError("a brand needs a name")
    slug = slug or slugify(name)
    if not SLUG.match(slug):
        raise PackError(f"'{slug}' is not a usable short name: lower-case letters, digits and hyphens, starting with a letter (2 to 40 characters)")
    cols = [_hex(c) for c in accents if str(c).strip()]
    if not cols:
        raise PackError("a brand needs at least one colour: --color '#RRGGBB'")
    palette = {}
    neutrals = starter()["neutrals"]
    for mode, dark in (("print", False), ("screen", True)):
        n = json.loads(json.dumps(neutrals[mode]))
        acc = _accents(cols, n["bg_primary"], dark)
        palette[mode] = {**{f"accent_{i + 1}": a for i, a in enumerate(acc)},
                         "accent_text_cool": cl.ensure_contrast(acc[0], n["bg_primary"], 4.5)[0],
                         "accent_text_warm": cl.ensure_contrast(acc[1], n["bg_primary"], 4.5)[0],
                         **n, "sequential": _ramp(acc[0], dark)}
    light = logo_light or logo_dark or placeholder_logo(palette["print"]["accent_1"], True)
    darkm = logo_dark or logo_light or placeholder_logo(palette["screen"]["accent_1"], False)
    brand = {
        "identity": {"slug": slug, "name": name, "owner": owner or name, **({"homepage": homepage} if homepage else {}), **({"tagline": tagline} if tagline else {})},
        "palette": palette,
        "typography": {"primary_family": "Inter"},
        "logo": {"dark": darkm, "light": light},
        "voice": {"register": "professional", "principles": ["Say what the map shows, plainly."], "prohibited": []},
    }
    if trademark_line:
        brand["ip_rules"] = {"disclaimer": trademark_line.strip()}
    return brand



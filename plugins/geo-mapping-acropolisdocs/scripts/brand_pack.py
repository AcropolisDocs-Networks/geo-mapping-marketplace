#!/usr/bin/env python3
"""brand_pack (1.7.0): everything that turns a brand into a map brand pack, at run time.

A brand pack is a folder of three files: `brand.json` (identity, palette for print and screen, logo, voice: the AcropolisDocs brand
registry format, schemas/brand.schema.json), `map-tokens.yaml` (the map's own colour roles, derived once here and stored, never computed
while a map is drawn) and `PACK.json` (hashes and where it came from). The plugin ships one pack, its default brand; any other brand is a
pack a person adds (set_brand.py add / new), kept outside the plugin so it survives updates.

The derivation below was the build tool's until 1.7.0 (tools/import_brand.py, which now imports it from here), so a pack added by a user
gets exactly the tokens a bundled pack gets: contrast floors, colour-vision distinctness, the dark-ground rules.
"""

SCHEMA = HERE.parent / "schemas" / "brand.schema.json"
SLUG = re.compile(r"^[a-z][a-z0-9-]{1,39}$")
PACK_FILES = ("brand.json", "map-tokens.yaml", "PACK.json")
LOGO_MAX_BYTES = 256 * 1024
TOKENS_HEADER = "# Generated by brand_pack. Edit only the `overrides:` block; adding the brand again preserves it.\n"


class PackError(Exception):
    """A one-line, user-facing problem with a brand pack (never a traceback)."""


def sha256_file(p: Path) -> str:
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def validate(brand: dict) -> list[str]:
    import jsonschema
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    v = jsonschema.validators.validator_for(schema)(schema)
    return [f"{'/'.join(str(x) for x in e.absolute_path) or '<root>'}: {e.message}" for e in v.iter_errors(brand)]


MODES = ("print", "screen")

# Contrast floors: WCAG text 4.5:1, graphical objects 3:1.
LABEL_MIN = 4.5
CLASS_MIN = 3.0
CVD_DISTINCT_MIN = 15.0
CATEGORICAL_N = 8
# Dark (screen) map grounds (0.2.1). A brand's near-black is right for a page of text and wrong for a map: land, water and the
# locator disappear into it. The map lifts its own grounds and keeps them apart; the lint re-checks them (MAP-A11Y-006).
DARK_GROUND_MIN_L = 0.10      # HLS lightness: the page is never darker than a very dark grey (about 10% lightness), not black
DARK_LAND_MIN = 1.25          # land is at least this contrast lighter than the page, so the map's shapes read on it
DARK_WATER_DE_MIN = 12.0      # water differs from both page and land by at least this CIE delta E (it sits between them in lightness)
DARK_PANEL_MIN = 1.15         # legend and locator panels stand off the page
DARK_PANEL_FRAME_MIN = 1.6    # panel outlines against the panel
DARK_FRAME_MIN = 2.0          # the map frame and the locator outline against the page


# ---------------------------------------------------------------- token derivation

def derive_modes(brand: dict) -> tuple[dict, dict, list]:
    modes: dict = {}
    rules: dict = {}
    subs: list = []
    for mode in MODES:
        pal = brand["palette"][mode]
        t, r = derive_mode(brand, mode, pal, subs)
        modes[mode], rules[mode] = t, r
    if "print" in modes and "screen" in modes:
        p_cat, s_cat = modes["print"]["categorical"], modes["screen"]["categorical"]
        modes["screen"]["categorical"] = s_cat[:1] + match_order(p_cat[1:], s_cat[1:])      # position 0 stays the brand's own accent
        rules["screen"]["categorical"] += ("; positions 1-7 reordered so each is the nearest hue to the same position in print (0 stays the "
                                           "brand accent), so a MapSpec keeps its colors' meaning when its theme changes")
    return modes, rules, subs


def match_order(reference: list[str], colors: list[str]) -> list[str]:
    """`colors` reordered so position i is as close in hue as possible to reference[i] (the assignment with the least total hue distance;
    low-chroma colors compare by lightness order instead). A light map's categorical.1 that is green stays green in the dark theme."""
    import itertools

    def lch(c):
        L, a, b = cl.lab(c)
        return L, (a * a + b * b) ** 0.5, __import__("math").degrees(__import__("math").atan2(b, a)) % 360

    def dist(x, y):
        Lx, Cx, hx = lch(x)
        Ly, Cy, hy = lch(y)
        if min(Cx, Cy) < 12:                               # a grey or near-grey: compare chroma and lightness, not hue
            return abs(Cx - Cy) * 2 + abs(Lx - Ly) * 0.2
        dh = abs(((hx - hy + 180) % 360) - 180)
        return dh + abs(Cx - Cy) * 0.3
    n = min(len(reference), len(colors))
    if n > 9:
        return colors
    cost = [[dist(reference[i], colors[j]) for j in range(len(colors))] for i in range(n)]
    best = min(itertools.permutations(range(len(colors)), n), key=lambda p: sum(cost[i][p[i]] for i in range(n)))
    return [colors[j] for j in best] + [c for k, c in enumerate(colors) if k not in best]


def derive_mode(brand: dict, mode: str, pal: dict, subs: list) -> tuple[dict, dict]:
    t: dict = {}
    r: dict = {}
    bg = pal["bg_primary"]

    def put(name, value, rule):
        t[name] = value
        r[name] = rule

    def note(token, before, after, reason):
        subs.append({"mode": mode, "token": token, "from": before, "to": after, "reason": reason})

    info = pal["semantic"]["info"]
    hue = cl.hls(info)[0]
    if mode == "print":
        put("background", cl.norm_hex(bg), f"palette.{mode}.bg_primary")
        put("land", cl.norm_hex(pal["bg_surface"]), f"palette.{mode}.bg_surface")
        water = cl.from_hls(hue, 0.90, 0.30)
        put("water", water, "desaturated cool tint of semantic.info (hue kept, saturation 0.30, lightness 0.90)")
        put("frame", cl.norm_hex(pal["border_strong"]), f"palette.{mode}.border_strong")
        put("legend_frame", cl.norm_hex(pal["border_default"]), f"palette.{mode}.border_default")
        panel = cl.norm_hex(pal["bg_elevated"])
    else:
        bg, land, water, panel, panel_frame, frame = dark_grounds(pal, hue, note)
        put("background", bg, f"palette.screen.bg_primary lifted to HLS lightness {DARK_GROUND_MIN_L} (a very dark grey; a map never sits on black)")
        put("land", land, f"palette.screen.bg_surface, at least {DARK_LAND_MIN}:1 lighter than the background")
        put("water", water, f"cool tint of semantic.info between background and land in lightness, delta E >= {DARK_WATER_DE_MIN} from both")
        put("frame", frame, f"palette.screen.border_strong, at least {DARK_FRAME_MIN}:1 against the background")
        put("legend_frame", panel_frame, f"palette.screen.border_default, at least {DARK_PANEL_FRAME_MIN}:1 against the panel")
    label, changed = cl.ensure_contrast(pal["text_primary"], bg, LABEL_MIN)
    if changed:
        note("label", pal["text_primary"], label, f"label contrast below {LABEL_MIN}:1")
    put("label", label, f"palette.{mode}.text_primary")
    put("label_halo", cl.norm_hex(bg), f"palette.{mode}.bg_primary (halo guarantees label contrast over fills)")
    put("legend_bg", panel, f"palette.{mode}.bg_elevated" + ("" if mode == "print" else f", at least {DARK_PANEL_MIN}:1 against the background"))
    put("neutral_ramp", [cl.mix(t["land"], pal["text_tertiary"], i / 4) for i in range(5)],
        "5 steps interpolated bg_surface to text_tertiary")
    put("sequential_ramp", [cl.norm_hex(c) for c in pal["sequential"]], f"palette.{mode}.sequential (stored 7-step ramp, resampled to the class count at render)")
    emph, changed = ensure_on_grounds(pal["accent_1"], (bg, t["land"], t["water"]), CLASS_MIN)
    if changed:
        note("emphasis", pal["accent_1"], emph, f"emphasis contrast below {CLASS_MIN}:1 against the background, land or water")
    put("emphasis", emph, f"palette.{mode}.accent_1")

    status = {}
    for k in ("success", "warning", "danger"):
        c, changed = ensure_on_grounds(pal["semantic"][k], (bg, t["land"]), CLASS_MIN)
        if changed:
            note(f"status.{k}", pal["semantic"][k], c, f"status contrast below {CLASS_MIN}:1")
        status[k] = c
    put("status", status, "semantic.success / warning / danger (always paired with a shape or label, MAP-A11Y-003)")

    # categorical: brand accents first, greys demoted, then derived hues
    accents = [pal[k] for k in ("accent_1", "accent_2", "accent_3", "accent_4", "accent_5") if k in pal]
    chosen: list[str] = []
    greys: list[str] = []
    cat_notes: list[str] = []
    for i, c in enumerate(accents, 1):
        name = f"accent_{i}"
        if cl.is_grey(c):
            greys.append(cl.norm_hex(c))
            cat_notes.append(f"{name} {cl.norm_hex(c)} is a brand grey: demoted to the 'no data / other' role")
            continue
        adj, changed = ensure_on_grounds(c, (bg, t["land"]), CLASS_MIN)
        if changed:
            note(f"categorical.{name}", c, adj, f"class color contrast below {CLASS_MIN}:1")
        if chosen and min(cl.cvd_min_delta_e(adj, o) for o in chosen) < CVD_DISTINCT_MIN:
            cat_notes.append(f"{name} {cl.norm_hex(c)} dropped: not distinct from an earlier class color under color-vision simulation")
            note(f"categorical.{name}", c, "(dropped)", f"delta E below {CVD_DISTINCT_MIN} under CVD simulation")
            continue
        chosen.append(adj)
        cat_notes.append(f"{name} kept as class color")
    pool = derived_hues(mode, bg, t["land"])
    while len(chosen) < CATEGORICAL_N:
        best = max(pool, key=lambda p: min(cl.cvd_min_delta_e(p, o) for o in chosen) if chosen else 0)
        chosen.append(best)
        pool = [p for p in pool if p != best]
    put("categorical", chosen[:CATEGORICAL_N], "brand accents that pass contrast and CVD distinctness, then derived hues (greedy farthest-first); " + "; ".join(cat_notes))
    nodata = greys[0] if greys else t["neutral_ramp"][2]
    put("no_data", nodata, "first brand grey, else neutral_ramp[2]")

    # diverging: two single-hue ramps with a neutral midpoint
    acc = emph
    info_c, _ = cl.ensure_contrast(info, bg, CLASS_MIN)
    rule_extra = ""
    if cl.hls(acc)[0] - cl.hls(info_c)[0] in (0.0,) or abs(((cl.hls(acc)[0] - cl.hls(info_c)[0] + 180) % 360) - 180) < 40:
        # accent and info share a hue: take the derived hue farthest from the accent
        far = max(derived_hues(mode, bg), key=lambda p: abs(((cl.hls(p)[0] - cl.hls(acc)[0] + 180) % 360) - 180))
        info_c = far
        rule_extra = "; semantic.info shares the accent hue, so the opposite end uses the derived hue farthest from the accent"
    mid = t["land"] if mode == "screen" else cl.norm_hex(pal["bg_elevated"])
    lo = [cl.mix(mid, info_c, k / 3) for k in (3, 2, 1)]
    hi = [cl.mix(mid, acc, k / 3) for k in (1, 2, 3)]
    put("diverging_ramp", lo + [mid] + hi, "single-hue ramps from semantic.info and accent_1 meeting at a neutral midpoint" + rule_extra)
    return t, r


def derived_hues(mode: str, bg: str, land: str | None = None) -> list[str]:
    light = 0.40 if mode == "print" else 0.62
    out = []
    for hue in range(0, 360, 20):
        c, _ = ensure_on_grounds(cl.from_hls(hue, light, 0.55), (bg, land or bg), CLASS_MIN)
        out.append(c)
    return out


def ensure_on_grounds(color: str, grounds, minimum: float) -> tuple[str, bool]:
    """`color` moved in lightness until it reaches `minimum` contrast on every ground (data sits on land and water, not only the page)."""
    c, changed = cl.norm_hex(color), False
    for _ in range(3):
        moved = False
        for g in grounds:
            c2, ch = cl.ensure_contrast(c, g, minimum)
            if ch:
                c, changed, moved = c2, True, True
        if not moved:
            break
    return c, changed


def _lift(color: str, min_l: float) -> str:
    h, l, s = cl.hls(color)
    return cl.norm_hex(color) if l >= min_l else cl.from_hls(h, min_l, s)


def _lighter_until(color: str, ground: str, minimum: float) -> str:
    """`color` made lighter (never darker) until it reaches `minimum` contrast against a darker `ground`."""
    h, l, s = cl.hls(color)
    c = cl.norm_hex(color)
    while cl.contrast(c, ground) < minimum and l < 1.0:
        l = min(1.0, l + 0.005)
        c = cl.from_hls(h, l, s)
    return c


def dark_grounds(pal: dict, hue: float, note) -> tuple[str, str, str, str, str, str]:
    """The dark theme's grounds: page, land, water, panel, panel outline and frame, by the DARK_* rules."""
    bg = _lift(pal["bg_primary"], DARK_GROUND_MIN_L)
    if bg != cl.norm_hex(pal["bg_primary"]):
        note("background", pal["bg_primary"], bg, f"a map is not drawn on black: lifted to HLS lightness {DARK_GROUND_MIN_L}")
    land = _lighter_until(_lift(pal["bg_surface"], DARK_GROUND_MIN_L), bg, DARK_LAND_MIN)
    if land != cl.norm_hex(pal["bg_surface"]):
        note("land", pal["bg_surface"], land, f"land contrast with the page below {DARK_LAND_MIN}:1")
    l_bg, l_land = cl.hls(bg)[1], cl.hls(land)[1]
    best = None
    for sat in (0.30, 0.35, 0.40):
        for i in range(21):
            lt = l_bg + (l_land - l_bg) * i / 20
            w = cl.from_hls(hue, lt, sat)
            score = min(cl.delta_e(w, bg), cl.delta_e(w, land))
            if best is None or score > best[0]:
                best = (score, w)
    water = best[1]
    if best[0] < DARK_WATER_DE_MIN:
        note("water", water, water, f"water only reaches delta E {best[0]:.1f} from page and land (wanted {DARK_WATER_DE_MIN})")
    panel = _lighter_until(cl.norm_hex(pal["bg_elevated"]), bg, DARK_PANEL_MIN)
    panel_frame = _lighter_until(cl.norm_hex(pal["border_default"]), panel, DARK_PANEL_FRAME_MIN)
    frame = _lighter_until(cl.norm_hex(pal["border_strong"]), bg, DARK_FRAME_MIN)
    return bg, land, water, panel, panel_frame, frame



def build_tokens(brand: dict, slug: str, source_sha: str, existing: dict | None, generated_by: str = "scripts/brand_pack.py") -> dict:
    modes, rules, subs = derive_modes(brand)
    overrides = (existing or {}).get("overrides") or {}
    for mode, toks in overrides.items():
        for name, value in (toks or {}).items():
            modes[mode][name] = value
            rules[mode][name] = "hand override"
    prefix = (brand.get("naming_overrides") or {}).get("prefix") or f"{slug}_"
    return {
        "schema": "map-tokens/1",
        "brand": slug,
        "source_sha256": source_sha,
        "typeface": "Inter",
        "output_prefix": prefix,
        "generated_by": generated_by,
        "modes": modes,
        "rules": rules,
        "substitutions": subs,
        "overrides": overrides,
    }




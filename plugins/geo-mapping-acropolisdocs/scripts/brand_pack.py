def read_logo(path) -> str:
    """A logo file as a checked SVG string. An SVG is checked as it is (clean_svg). 1.8.0: a PNG or JPEG is carried inside a plain SVG wrapper
    at its own pixel size; a vector mark stays sharper at every size, so the message says so once."""
    import base64
    f = Path(path).expanduser()
    if not f.is_file():
        raise PackError(f"no logo file at {f}")
    ext = f.suffix.lower()
    if ext not in RASTER_LOGOS:
        if f.stat().st_size > LOGO_MAX_BYTES * 2:
            raise PackError(f"{f.name} is larger than a logo can be; export a simpler SVG")
        return clean_svg(f.read_text(encoding="utf-8", errors="replace"), f"logo {f.name}")
    raw = f.read_bytes()
    if len(raw) > RASTER_MAX_BYTES:
        raise PackError(f"{f.name} is {len(raw) // 1024} KB; a PNG or JPEG logo can be up to {RASTER_MAX_BYTES // 1024} KB (a logo is drawn small: "
                        "600 pixels wide is plenty), or give an SVG")
    try:
        import io
        from PIL import Image
        with Image.open(io.BytesIO(raw)) as im:
            im.verify()
        with Image.open(io.BytesIO(raw)) as im:
            w, h, fmt = im.width, im.height, (im.format or "").upper()
    except ImportError:
        raise PackError("a PNG or JPEG logo needs the Pillow package (it comes with the map packages); or give an SVG") from None
    except Exception:  # noqa: BLE001 - whatever Pillow says, the answer for the person is the same
        raise PackError(f"{f.name} is not a readable PNG or JPEG image") from None
    if fmt not in ("PNG", "JPEG") or w < 16 or h < 16 or w > 4000 or h > 4000:
        raise PackError(f"{f.name} must be a PNG or JPEG between 16 and 4,000 pixels a side")
    mime = "image/png" if fmt == "PNG" else "image/jpeg"
    return clean_svg(starter()["raster_logo"].format(w=w, h=h, mime=mime, b64=base64.b64encode(raw).decode("ascii")), f"logo {f.name}")


def _logo_box(svg: str) -> tuple[str, float] | None:
    m = re.search(r'viewBox\s*=\s*["\']\s*([-0-9.eE]+)[ ,]+([-0-9.eE]+)[ ,]+([0-9.eE]+)[ ,]+([0-9.eE]+)', svg)
    if not m:
        return None
    w, h = float(m.group(3)), float(m.group(4))
    return (f"{m.group(1)} {m.group(2)} {m.group(3)} {m.group(4)}", round(w / h, 3)) if w > 0 and h > 0 else None


def clean_brand(brand: dict) -> dict:
    """Every SVG in the brand's logo block checked (clean_svg), and viewBox and ratio filled in from the mark when the brand left them out."""
    logo = brand.get("logo")
    if not isinstance(logo, dict):
        raise PackError("the brand has no logo block")

    def walk(d: dict, label: str):
        for k, v in list(d.items()):
            if isinstance(v, str) and "<svg" in v:
                d[k] = clean_svg(v, f"{label} logo ({k})")
            elif isinstance(v, dict):
                walk(v, k)

    walk(logo, "brand")
    box = _logo_box(logo.get("light") or logo.get("dark") or "")
    if box:
        logo.setdefault("viewBox", box[0])
        logo.setdefault("ratio", box[1])
    return brand


# ---------------------------------------------------------------- writing a pack

def write_pack(brand: dict, dest_root: Path, accreditation: dict, *, source: dict | None = None, reserved: tuple = (), replace: bool = False) -> dict:
    """Write DEST_ROOT/<slug>/{brand.json, map-tokens.yaml, PACK.json} for a checked brand. `reserved` are the slugs the plugin ships (a
    person's pack never takes their place). An existing pack is replaced only with replace=True; its `overrides:` block is kept."""
    import yaml
    errs = validate(brand)
    if errs:
        raise PackError("the brand file does not fit the brand format: " + "; ".join(errs[:4]) + (f" (and {len(errs) - 4} more)" if len(errs) > 4 else ""))
    slug = brand["identity"]["slug"]
    if not SLUG.match(slug):
        raise PackError(f"'{slug}' is not a usable short name: lower-case letters, digits and hyphens, starting with a letter (2 to 40 characters)")
    if slug in reserved:
        raise PackError(f"'{slug}' is the plugin's own brand and cannot be replaced; give your brand another short name")
    brand = clean_brand(json.loads(json.dumps(brand)))
    dest = Path(dest_root) / slug
    if dest.exists() and not replace:
        raise PackError(f"a brand named '{slug}' is already here ({dest}); add it again with --replace to update it")
    existing = None
    if (dest / "map-tokens.yaml").is_file():
        try:
            existing = yaml.safe_load((dest / "map-tokens.yaml").read_text(encoding="utf-8"))
        except Exception:  # noqa: BLE001 - an unreadable old file has no overrides to keep
            existing = None
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "brand.json").write_text(json.dumps(brand, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    sha = sha256_file(dest / "brand.json")
    tokens = build_tokens(brand, slug, sha, existing)
    (dest / "map-tokens.yaml").write_text(TOKENS_HEADER + yaml.safe_dump(tokens, sort_keys=False, width=120), encoding="utf-8")
    pack = {
        "schema": "brand-pack/1", "slug": slug, "house": False, "origin": "user",
        "source": source or {"kind": "user"},
        "imported_on": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "source_sha256": sha,
        "files": {"brand.json": sha, "map-tokens.yaml": sha256_file(dest / "map-tokens.yaml")},
        "accreditation": accreditation,
        "trademark_line": (brand.get("ip_rules") or {}).get("disclaimer"),
        "ignored_from_brand": ["typography", "assets.pptx_template", "palette gradient strings"],
    }
    (dest / "PACK.json").write_text(json.dumps(pack, indent=2) + "\n", encoding="utf-8")
    return {"slug": slug, "name": brand["identity"]["name"], "dir": str(dest), "substitutions": tokens["substitutions"]}


def read_source(path: Path) -> tuple[dict, dict | None]:
    """(brand, overrides or None) from a pack folder, a brand.json or any brand file in the AcropolisDocs brand registry format."""
    import yaml
    p = Path(path)
    f = p / "brand.json" if p.is_dir() else p
    if not f.is_file():
        raise PackError(f"no brand file at {p} (give a pack folder that holds brand.json, or a brand .json file)")
    if f.stat().st_size > 4 * 1024 * 1024:
        raise PackError(f"{f.name} is larger than a brand file can be (4 MB)")
    try:
        brand = json.loads(f.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise PackError(f"{f.name} is not readable JSON: {str(e)[:100]}") from None
    if not isinstance(brand, dict) or "identity" not in brand:
        raise PackError(f"{f.name} is not a brand file (it has no identity block)")
    overrides = None
    tok = f.parent / "map-tokens.yaml"
    if tok.is_file():
        try:
            overrides = (yaml.safe_load(tok.read_text(encoding="utf-8")) or {}).get("overrides") or None
        except Exception:  # noqa: BLE001
            overrides = None
    return brand, overrides


def install(path: Path, dest_root: Path, accreditation: dict, *, reserved: tuple = (), replace: bool = False) -> dict:
    """Add the brand at PATH (pack folder or brand file) to DEST_ROOT. The tokens are always derived again here, never trusted from the
    source; only its hand `overrides:` block is carried over."""
    import yaml
    brand, overrides = read_source(Path(path))
    slug = (brand.get("identity") or {}).get("slug")
    if overrides and isinstance(slug, str) and SLUG.match(slug) and slug not in reserved:
        d = Path(dest_root) / slug
        if not (d / "map-tokens.yaml").is_file() or replace:
            d.mkdir(parents=True, exist_ok=True)
            (d / "map-tokens.yaml").write_text(yaml.safe_dump({"overrides": overrides}), encoding="utf-8")
            replace = True
    return write_pack(brand, dest_root, accreditation, source={"kind": "user", "from": Path(path).name}, reserved=reserved, replace=replace)


def remove(slug: str, root: Path) -> bool:
    d = Path(root) / slug
    if not SLUG.match(slug) or not (d / "PACK.json").is_file():
        return False
    shutil.rmtree(d)
    return True

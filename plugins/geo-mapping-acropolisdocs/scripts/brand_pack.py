_SVG_BAD = [
    (re.compile(r"<\s*script\b", re.I), "a <script> element"),
    (re.compile(r"<\s*(foreignObject|iframe|object|embed|audio|video|handler|listener|set|animate\w*)\b", re.I), "an embedded or animated element"),
    (re.compile(r"\son[a-z]+\s*=", re.I), "an event handler attribute (on...=)"),
    (re.compile(r"javascript\s*:", re.I), "a javascript: address"),
    (re.compile(r"<!\s*(ENTITY|DOCTYPE)", re.I), "a DOCTYPE or entity declaration"),
    (re.compile(r"(?:href|src)\s*=\s*[\"']\s*(?!#|data:image/(?:png|jpeg|gif|webp);base64,)[^\"']", re.I), "a link to something outside the file"),
    (re.compile(r"url\(\s*[\"']?\s*(?!#)[^)\s]", re.I), "a url() that points outside the file"),
    (re.compile(r"@import|expression\s*\(", re.I), "a stylesheet import"),
]


def clean_svg(text: str, what: str = "logo") -> str:
    """The SVG as one plain drawing, or PackError saying what it holds that a map page must not carry. A logo is drawn into web pages and
    PDFs as markup, so it may hold shapes, paths, gradients and its own styles, and nothing that runs, loads or links."""
    if not isinstance(text, str):
        raise PackError(f"the {what} is not SVG text")
    t = text.lstrip("﻿").strip()
    t = re.sub(r"^<\?xml[^>]*\?>\s*", "", t)
    t = re.sub(r"<!--.*?-->", "", t, flags=re.S).strip()
    if len(t.encode("utf-8")) > LOGO_MAX_BYTES:
        raise PackError(f"the {what} is larger than {LOGO_MAX_BYTES // 1024} KB; export a simpler SVG")
    if not re.match(r"<svg[\s>]", t, re.I) or not t.rstrip().endswith("</svg>"):
        raise PackError(f"the {what} is not an SVG file (it must start with <svg and end with </svg>)")
    for rx, why in _SVG_BAD:
        if rx.search(t):
            raise PackError(f"the {what} holds {why}; a logo must be a plain drawing. Export it again as plain SVG (outlined text, no scripts or links)")
    try:
        from lxml import etree
        root = etree.fromstring(t.encode("utf-8"), etree.XMLParser(resolve_entities=False, no_network=True, load_dtd=False, huge_tree=False))
        if etree.QName(root).localname != "svg":
            raise PackError(f"the {what} is not an SVG drawing")
        if not root.get("viewBox"):
            w, h = root.get("width"), root.get("height")
            m = [re.match(r"^\s*([0-9.]+)", str(x or "")) for x in (w, h)]
            if not all(m):
                raise PackError(f"the {what} has no viewBox (and no width and height to make one from)")
            box = f' viewBox="0 0 {m[0].group(1)} {m[1].group(1)}"'
            t = re.sub(r"<svg\b", lambda hit: hit.group(0) + box, t, count=1, flags=re.I)
    except ImportError:                                   # lxml comes with the map packages; without it the pattern checks above still hold
        pass
    except PackError:
        raise
    except Exception as e:  # noqa: BLE001 - a parser message, shortened, is the user's answer
        raise PackError(f"the {what} is not well-formed SVG: {str(e)[:120]}") from None
    return t


RASTER_LOGOS = {".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg"}

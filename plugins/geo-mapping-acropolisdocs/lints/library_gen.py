"""Generated library files (spec 9.3.6, 9.3.7): index.yaml and CHANGELOG.md. Deterministic: the same entries give the same text.

MAP-LIB-011 compares what is on disk with what these functions render, so a hand edit or a forgotten regeneration is caught.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import yaml

INDEX_NOTE = "GENERATED by tools/ref_release.py from library/entries; do not edit by hand."


def _digest(o) -> str:
    return hashlib.sha256(json.dumps(o, sort_keys=True, default=str).encode()).hexdigest()[:12]


def _clean(e: dict) -> dict:
    return {k: v for k, v in e.items() if not k.startswith("_")}


def render_index(entries: list[dict], lib: Path) -> str:
    rows = []
    for e in sorted(entries, key=lambda x: str(x.get("id"))):
        p = Path(e["_path"])
        try:
            rel = p.relative_to(lib).as_posix()
        except ValueError:
            rel = p.name
        rows.append({"id": e.get("id"), "file": rel, "type": e.get("type"), "status": e.get("status"), "rev": e.get("rev"),
                     "tags_digest": _digest(e.get("tags") or {}), "entry_digest": _digest(_clean(e))})
    return "# " + INDEX_NOTE + "\n" + yaml.safe_dump({"entries": rows}, sort_keys=False)


def render_changelog(entries: list[dict]) -> str:
    lines = []
    for e in entries:
        for c in (e.get("maintenance") or {}).get("changelog") or []:
            if isinstance(c, dict):
                lines.append((str(c.get("date")), str(e.get("id")), c.get("rev"), str(c.get("note", "")).strip()))
    lines.sort(key=lambda x: (x[1], x[2] if isinstance(x[2], int) else 0))
    lines.sort(key=lambda x: x[0], reverse=True)            # newest date first, then id and rev in order (the sort is stable)
    out = ["# Reference library changelog", "", "GENERATED from the `maintenance.changelog` of every entry; do not edit by hand.", ""]
    cur = None
    for date, eid, rev, note in lines:
        if date != cur:
            out += ["", f"## {date}", ""]
            cur = date
        out.append(f"- `{eid}` rev {rev}: {note}")
    return "\n".join(out).replace("\n\n\n", "\n\n") + "\n"
